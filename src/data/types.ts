export type EntryType = 'film' | 'series' | 'special' | 'short' | 'animated'

export type Entry = {
  /** Official story order (Marvel Disney+ Complete Timeline, June 2026). Fractions are unofficial insertions. */
  o: number
  /** Unique slug. */
  id: string
  /** Title. Series seasons end in " S2", " S3"… */
  t: string
  type: EntryType
  /** Phase 1–6; 0 = Netflix/ABC/Hulu/Fox (non-Studios). */
  ph: number
  canon?: 'netflix' | 'abc' | 'hulu'
  /** In-universe year, used for axis labels. */
  year: number
  /** Display override for "set in" (e.g. "1942 – 1945", "outside time (TVA)"). */
  yl?: string
  /** Release date, YYYY-MM-DD. */
  rel: string
  /** "124 min" / "6 episodes" */
  run: string
  /** "Disney+" / "Theaters" */
  watch: string
  /** Verified official URL; if absent, the TMDB watch page is used. */
  link?: string
  /** Alternate universe: dashed styling plus a branch link to the main thread. */
  alt?: boolean
  /** Alternates only: id of the title the branch starts from, instead of the nearest main-timeline title before it. */
  branchFrom?: string
  /** Alternates only: titles sharing a line are joined into one dashed thread in story order, and only the first one visible branches off. */
  line?: string
  /** Fox X-Men film, hidden unless the X-Men toggle is on. */
  fox?: boolean
  /** Placement is not official. */
  disputed?: boolean
  /** Shown in the detail modal in amber. */
  note?: string
  /** Number on Disney's list of titles to watch before Avengers: Doomsday (October 2026). Seasons of one show share a number. */
  essential?: number
  /** Synopsis. */
  syn: string
}

/** TMDB match for an entry, generated by `npm run tmdb` into tmdb.json. */
export type TmdbMatch = {
  type: 'movie' | 'tv'
  id: number
  /** Poster path, e.g. "/abc123.jpg"; null when TMDB has no poster. */
  poster: string | null
}
